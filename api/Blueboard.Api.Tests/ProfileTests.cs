using System.Security.Claims;
using System.Text.Json;
using Blueboard.Api.Auth;
using Blueboard.Contracts;
using Xunit;

namespace Blueboard.Api.Tests;

/// <summary>Agent names: the defaults for app-only tokens and the handle rules set_profile and the admin rename share.</summary>
public class ProfileTests
{
    private const string AppId = "0a1b2c3d-4e5f-4a6b-8c7d-9e0f1a2bc0de";

    [Fact]
    public void V2_app_token_without_a_name_gets_an_agent_handle_not_a_guid()
    {
        var id = TokenValidator.FromClaims(new ClaimsIdentity([new("oid", "0a1b2c3d-0000-0000-0000-000000000000"), new("idtyp", "app"), new("azp", AppId)]));
        Assert.Equal(AppId, id.Name); // what the token gives us
        var (handle, name) = Handles.Default(id);
        Assert.Equal("agent-0a1b2c3d", handle);
        Assert.Equal("Agent 0a1b2c3d", name);
        Assert.True(Handles.IsAutoGenerated(handle));
    }

    [Fact]
    public void Named_tokens_keep_their_names()
    {
        var app = TokenValidator.FromClaims(new ClaimsIdentity([new("oid", "o1"), new("idtyp", "app"), new("azp", AppId), new("app_displayname", "Triage Bot")]));
        Assert.Equal(("triage-bot", "Triage Bot"), Handles.Default(app));
        var person = TokenValidator.FromClaims(new ClaimsIdentity([new("oid", "o2"), new("scp", "Board.Access"), new("preferred_username", "ana.lopez@contoso.com"), new("name", "Ana Lopez")]));
        Assert.Equal(("ana-lopez", "Ana Lopez"), Handles.Default(person));
    }

    [Theory]
    [InlineData("0a1b2c3d-4e5f-4a6b-8c7d-9e0f1a2b", true)]   // the handle old principals got from a client id
    [InlineData("agent-0a1b2c3d", true)]
    [InlineData("agent-0a1b2c3d-0a1b2c", true)]              // with the clash suffix
    [InlineData("enrichment-agent", false)]
    [InlineData("agent-smith", false)]
    [InlineData("deadbeef", false)]
    public void Auto_generated_handles_are_recognised(string handle, bool generated) =>
        Assert.Equal(generated, Handles.IsAutoGenerated(handle));

    [Theory]
    [InlineData("Enrichment Agent", "enrichment-agent")]
    [InlineData("@triage_bot!!", "triage-bot")]
    [InlineData("--x--", "x")]
    [InlineData("a-very-long-handle-that-goes-past-the-limit", "a-very-long-handle-that-goes-pas")]
    public void Handles_are_normalised_like_first_sign_in(string input, string expected) =>
        Assert.Equal(expected, Handles.Normalise(input));

    [Fact]
    public void Profile_contract_bounds_its_fields()
    {
        Assert.Throws<ContractException>(() => Contract.Read<ProfileInput>(JsonSerializer.SerializeToElement(new { display_name = new string('x', 65) })));
        Assert.Throws<ContractException>(() => Contract.Read<ProfileInput>(JsonSerializer.SerializeToElement(new { handle = "x" })));
        var p = Contract.Read<ProfileInput>(JsonSerializer.SerializeToElement(new { handle = "enrichment-agent" }));
        Assert.Null(p.DisplayName);
    }
}
